#!/usr/bin/env python3
"""Validate internal links and heading anchors of the bilingual wiki sources.

GitHub Wiki pages are flat: a link is written as ``[text](Page-Name)`` and a deep
link as ``[text](Page-Name#heading-slug)``. This script mimics GitHub's heading
slug algorithm and reports:

  * links to pages that do not exist
  * deep links whose anchor does not match any heading of the target page
  * duplicate headings inside one page (ambiguous anchors)

Chinese and English pages are checked together, so the cross-language links
(``Home`` -> ``Home-EN``) resolve as well.

Usage:
    python3 scripts/check-wiki-links.py                # check docs/wiki/zh and en
    python3 scripts/check-wiki-links.py docs/wiki/en   # check one directory
Exit code: 0 when everything resolves, 1 otherwise.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Characters GitHub drops when building a heading slug.
PUNCT = set('!"#$%&\'()*+,./:;<=>?@[\\]^`{|}~' '–—、。，！？：；「」『』（）《》〈〉·…')
LINK_RE = re.compile(r"\[[^\]]*\]\((?P<target>[^)\s]+)(?:\s+\"[^\"]*\")?\)")
HEADING_RE = re.compile(r"^#{1,6}\s+(?P<text>.+?)\s*$", re.MULTILINE)
CODE_FENCE_RE = re.compile(r"^```[^\n]*\n.*?^```[^\n]*$", re.MULTILINE | re.DOTALL)
EXTERNAL = re.compile(r"^(https?:|mailto:|ftp:|#)")
IGNORED_SUFFIX = (".png", ".jpg", ".jpeg", ".svg", ".zip", ".xlsx", ".step", ".STEP", ".epro2")
GENERATED = {"_Sidebar"}  # generated by scripts/sync-wiki.*


def slug(text: str) -> str:
    text = text.strip().lower()
    out = []
    for ch in text:
        if ch in PUNCT:
            continue
        out.append("-" if ch.isspace() else ch)
    return "".join(out)


def headings(text: str) -> list[str]:
    # A '#' comment at the start of a line inside a fenced block is not a heading.
    text = CODE_FENCE_RE.sub("", text)
    return [m.group("text").rstrip("#").strip() for m in HEADING_RE.finditer(text)]


def collect(directories: list[Path]) -> dict[str, Path]:
    pages: dict[str, Path] = {}
    for directory in directories:
        for path in sorted(directory.glob("*.md")):
            if path.stem in GENERATED:
                continue
            if path.stem in pages:
                print(f"warning: duplicate page name {path.stem} "
                      f"({pages[path.stem]} and {path})")
            pages[path.stem] = path
    return pages


def check(directories: list[Path]) -> list[str]:
    pages = collect(directories)
    anchors = {
        name: {slug(h) for h in headings(path.read_text(encoding="utf-8"))}
        for name, path in pages.items()
    }
    errors: list[str] = []

    for name, path in pages.items():
        text = path.read_text(encoding="utf-8")

        seen: dict[str, int] = {}
        for heading in headings(text):
            key = slug(heading)
            seen[key] = seen.get(key, 0) + 1
        for dup, count in seen.items():
            if count > 1:
                errors.append(f"{path.name}: duplicate heading slug #{dup} ({count}x)")

        for m in LINK_RE.finditer(text):
            target = m.group("target")
            if EXTERNAL.match(target) or target.endswith(IGNORED_SUFFIX):
                continue
            if target.startswith(("./", "../")):
                if not (path.parent / target).resolve().exists():
                    errors.append(f"{path.name}: missing file link -> {target}")
                continue
            page, _, anchor = target.partition("#")
            page = page.removesuffix(".md")
            if page not in pages:
                errors.append(f"{path.name}: missing page -> {target}")
                continue
            if anchor and anchor not in anchors[page]:
                errors.append(f"{path.name}: missing anchor -> {target}")
    return errors


def main(argv: list[str]) -> int:
    directories = [Path(a).resolve() for a in argv[1:]] or [
        ROOT / "docs/wiki/zh",
        ROOT / "docs/wiki/en",
    ]
    missing = [d for d in directories if not d.is_dir()]
    for directory in missing:
        print(f"skip: {directory} (not a directory)")
    directories = [d for d in directories if d.is_dir()]

    errors = check(directories)
    scope = ", ".join(str(d) for d in directories)
    if errors:
        print(f"{scope}: {len(errors)} problem(s)")
        for error in errors:
            print(f"  - {error}")
        return 1
    print(f"{scope}: OK ({len(collect(directories))} pages)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
